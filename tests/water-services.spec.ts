import { test, expect } from "@playwright/test";

test("dasbor Aetra, filter periode, pencarian, dan ekspor laporan", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Selamat.*Rani/ })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Air bersih, kehidupan lebih baik." })).toBeVisible();
  await expect(page.getByRole("button", { name: /Total pendaftaran/ })).toContainText("128");
  await page.getByLabel("Periode ringkasan").selectOption("previous");
  await expect(page.getByRole("button", { name: /Total pendaftaran/ })).toContainText("108");
  await page.getByLabel("Periode ringkasan").selectOption("month");
  await page.getByRole("button", { name: "Harian", exact: true }).click();
  await page.getByRole("button", { name: "Cari pendaftaran atau tiket" }).click();
  await page.getByPlaceholder("Contoh: Budi Santoso atau Sepatan").fill("Budi Santoso");
  await expect(page.getByRole("dialog").getByRole("button", { name: /Budi Santoso/ }).first()).toBeVisible();
  await page.getByRole("dialog").getByRole("button", { name: /Budi Santoso/ }).first().click();
  await expect(page.getByRole("heading", { name: "Budi Santoso" })).toBeVisible();
  await expect(page.getByText("Peruntukan sambungan", { exact: true })).toBeVisible();
  await page.goto("/#/dashboard");
  await page.getByRole("button", { name: "Unduh laporan", exact: true }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Unduh data pendaftaran (CSV)" }).click();
  expect((await download).suggestedFilename()).toMatch(/laporan-sambungan-air/);
  expect(errors).toEqual([]);
});

